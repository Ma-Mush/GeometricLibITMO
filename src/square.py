def area(a):
    '''
    Вычисляет площадь квадрата по его стороне.

    Параметры:
        a (число) :  Сторона квадрата.
    
    Возврат:
        area (число) : Площадь квадрата.

    Пример:
        area(10) -> 100
    '''
    return a * a


