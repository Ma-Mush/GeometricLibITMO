    '''
    Вычисляет периметр квадрата по его стороне.

    Параметры:
        a (число) :  Сторона квадрата.
    
    Возврат:
        perimeter (число) : Периметр квадрата.

    Пример:
        perimeter(10) -> 40
    '''
    return 4 * a